def test_ordered_clock_generator_and_poisoned_caches_preserve_predictions(
    source, report
):
    poisoned = replace(
        source,
        storage=I(-99),
        form_rates=(I(88),) * 12,
        phase_rates=(I(-77),) * 12,
    )
    rebuilt = _assess(poisoned, clock_scale_bounds=iter(BUDGET["clock_scale_bounds"]))
    assert rebuilt.ratio_prediction_bounds == report.ratio_prediction_bounds
    assert rebuilt.ideal_phase_curvature_bounds == report.ideal_phase_curvature_bounds
    with pytest.raises((TypeError, ValueError)):
        _assess(replace(source, capacity=(True,) + source.capacity[1:]))


def test_three_preparations_and_unknown_common_clock_survive_sdk_projection(
    report, tmp_path
):
    assert len(report.phase_initial_box) == 24
    assert report.phase_initial_form == (0,) * 12
    assert report.source.phase == (0,) * 12
    projected = relational_report_to_dict(report)
    destination = tmp_path / "clock-discrimination.json"
    export_to_json(projected, destination)
    saved = json.loads(destination.read_text())
    assert saved == projected
    data = saved["report"]
    assert data["sampling_duration"] == {"numerator": 1, "denominator": 50}
    assert len(data["ratio_prediction_bounds"]) == 2
    assert len(data["phase_initial_box"]) == 24
    assert data["discrimination_certified"]
