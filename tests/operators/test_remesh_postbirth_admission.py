def _configure(graph):
    graph.graph.update(
        REMESH_TAU_LOCAL=1,
        REMESH_TAU_GLOBAL=1,
        REMESH_ALPHA=0.5,
        REMESH_ALPHA_HARD=True,
        REMESH_LOG_EVENTS=False,
        CLIP_MODE="hard",
        EPI_MIN=-1.0,
        EPI_MAX=1.0,
    )
    graph.graph["GLYPH_FACTORS"]["AL_boost"] = 0.125


def _checkpoint(graph):
    return structural_proof_signature(
        (
            graph.graph,
            tuple(graph.nodes(data=True)),
            tuple(graph.edges(data=True)),
            hasattr(graph, "_last_operator_applied"),
            getattr(graph, "_last_operator_applied", None),
        ),
        opaque_references=(graph,),
    )


def _primitive_state(graph):
    return (
        tuple(
            (
                node,
                form(graph, node),
                get_attr(graph.nodes[node], ALIAS_VF),
                get_attr(graph.nodes[node], ALIAS_DNFR),
                get_attr(graph.nodes[node], ALIAS_THETA),
            )
            for node in graph
        ),
        deepcopy(tuple(graph.edges(data=True))),
        graph.graph["_t"],
    )


def _schedule(graph, word=("recursivity",)):
    return build_operator_event_schedule(
        word,
        start_time=graph.graph["_t"],
        flow_durations=(0.0,) * (len(word) + 1),
    )


def test_actual_advisory_does_not_supply_delayed_memory_or_execute_mixing():
    graph, parent, peer, child = build_source()
    _configure(graph)
    assert "_epi_hist" not in graph.graph
    before = _checkpoint(graph)
    insufficient = apply_network_remesh(graph)
    assert insufficient.status == "insufficient_history"
    assert not insufficient.applied
    assert _checkpoint(graph) == before

    structural = _primitive_state(graph)
    contexts = {node: read_grammar_state(graph.nodes[node]) for node in graph}
    temporal = {
        node: deepcopy(graph.nodes[node].get("epi_time_history")) for node in graph
    }
    result = execute_recursivity_stage(graph, Recursivity(), tuple(graph))
    assert result.glyph == "REMESH" and result.nodes_processed == 3
    assert _primitive_state(graph) == structural
    assert "_epi_hist" not in graph.graph and "_REMESH_META" not in graph.graph
    for node in (parent, peer, child):
        current = read_grammar_state(graph.nodes[node])
        assert current.operator_step == contexts[node].operator_step + 1
        assert current.history[-1] == "REMESH"
        assert graph.nodes[node].get("epi_time_history") == temporal[node]
    assert read_grammar_state(graph.nodes[child]).history == ("IL", "REMESH")


def test_two_actual_postbirth_samples_admit_cycle_without_elapsed_time_or_padding():
    graph, parent, peer, child = build_source()
    _configure(graph)
    first = append_remesh_epi_history_snapshot(graph)
    expected = {parent: 25 / 64, peer: 3 / 8, child: 15 / 128}
    assert first.snapshot_items == tuple(expected.items())
    assert (first.history_length_before, first.history_length_after) == (0, 1)
    assert first.history_maxlen == 64 and not first.oldest_snapshot_evicted
    history = graph.graph["_epi_hist"]
    before = _checkpoint(graph)
    assert apply_network_remesh(graph).status == "insufficient_history"
    assert _checkpoint(graph) == before

    primitive = _primitive_state(graph)
    result = execute_event_remesh_cycle(graph, _schedule(graph))
    assert result.remesh_applied and result.remesh.status == "applied"
    assert result.history_length_before_cycle == 1
    assert result.history_length_after_append == 2
    assert not result.history_oldest_snapshot_evicted
    assert graph.graph["_epi_hist"] is history
    assert list(history) == [expected, expected]
    assert result.pre_remesh_epi.epi_values == tuple(expected.values())
    assert result.post_remesh_epi.epi_values == tuple(expected.values())
    assert _primitive_state(graph) == primitive
    assert graph.graph["_t"] == 0.25
    assert tuple(graph.nodes[child]["epi_time_history"]) == ((0.25, 15 / 128),)
    assert read_grammar_state(graph.nodes[child]).history == ("IL", "REMESH")


@pytest.mark.parametrize("postbirth_samples", [1, 2])
def test_actual_prebirth_row_is_not_padded_and_selected_rows_differ_from_cycle_domain(
    postbirth_samples,
):
    graph, parent, peer, child = build_source(capture_prebirth=True)
    _configure(graph)
    history = graph.graph["_epi_hist"]
    assert len(history) == 1
    original_row = deepcopy(history[0])
    assert set(original_row) == {parent, peer} and child not in original_row
    for _ in range(postbirth_samples):
        sample = append_remesh_epi_history_snapshot(graph)
        assert tuple(node for node, _ in sample.snapshot_items) == (parent, peer, child)
    before = _checkpoint(graph)
    with pytest.raises(TNFRValueError, match="support must equal"):
        execute_event_remesh_cycle(graph, _schedule(graph))
    assert _checkpoint(graph) == before
    assert graph.graph["_epi_hist"] is history
    assert history[0] == original_row and child not in history[0]

    if postbirth_samples == 1:
        with pytest.raises(TNFRValueError, match="support must equal"):
            apply_network_remesh(graph)
        assert _checkpoint(graph) == before
    else:
        primitive = _primitive_state(graph)
        applied = apply_network_remesh(graph)
        assert applied.applied
        assert applied.plan.history_length == 3
        assert _primitive_state(graph) == primitive
        assert tuple(proposal.node for proposal in applied.plan.proposals) == (
            parent,
            peer,
            child,
        )
    assert history[0] == original_row and child not in history[0]
    assert graph.graph["_epi_hist"] is history
    assert read_grammar_state(graph.nodes[child]).history == ("IL",)
    assert form(graph, child) == Q(15, 128)


def test_actual_thol_birth_cannot_be_hidden_inside_a_fixed_node_cycle(monkeypatch):
    graph, parent, peer = build_prebirth_source()
    _configure(graph)
    graph.graph["GLYPH_FACTORS"]["OZ_dnfr_factor"] = 1.25
    graph.graph["OZ_ENABLE_PROPAGATION"] = False
    assert "_epi_hist" not in graph.graph

    require_node_order = cycle_runtime._require_node_order

    def observe_actual_birth(target, nodes, *, boundary):
        assert boundary == "after_schedule"
        assert tuple(target)[:2] == (parent, peer)
        assert len(target) == 3
        (child,) = target.nodes[parent]["sub_nodes"]
        assert child == tuple(target)[2]
        assert form(target, child) == Q(15, 128)
        assert read_grammar_state(target.nodes[child]).history == ()
        # Delegate unchanged: this observer supplies neither birth nor admission.
        return require_node_order(target, nodes, boundary=boundary)

    monkeypatch.setattr(cycle_runtime, "_require_node_order", observe_actual_birth)
    before = _checkpoint(graph)
    with pytest.raises(TNFRValueError, match="fixed ordered node support"):
        execute_event_remesh_cycle(
            graph,
            _schedule(
                graph,
                (
                    "recursivity",
                    "coherence",
                    "dissonance",
                    "self_organization",
                    "recursivity",
                ),
            ),
        )
    assert _checkpoint(graph) == before
    assert tuple(graph) == (parent, peer)
    assert "_epi_hist" not in graph.graph
    assert "sub_nodes" not in graph.nodes[parent]
    assert read_grammar_state(graph.nodes[parent]).operator_step == 6
    assert read_grammar_state(graph.nodes[peer]).operator_step == 4


def test_late_actual_mix_observer_failure_restores_postbirth_cycle_entry():
    graph, parent, peer, child = build_source()
    _configure(graph)
    append_remesh_epi_history_snapshot(graph)
    Emission()(graph, child, validate_preconditions=True)
    assert form(graph, child) == Q(31, 128)
    graph.graph["REMESH_LOG_EVENTS"] = True

    def corrupt_child_phase(target, _context):
        # This fault is reached only after the actual whole-network EPI map.
        assert form(target, child) == Q(19, 128)
        target.nodes[child]["theta"] = 1.0

    callback_manager.register_callback(
        graph,
        CallbackEvent.ON_REMESH,
        corrupt_child_phase,
        name="postbirth-remesh-phase-fault",
    )
    # Isolate the late observer boundary from dirty-registry normalization.
    callback_manager._ensure_callbacks(graph)
    assert "_callbacks_dirty" not in graph.graph
    history = graph.graph["_epi_hist"]
    before = _checkpoint(graph)
    with pytest.raises(TNFRValueError, match="capacity, pressure or phase"):
        execute_event_remesh_cycle(graph, _schedule(graph))
    assert _checkpoint(graph) == before
    assert graph.graph["_epi_hist"] is history and len(history) == 1
    assert tuple(graph) == (parent, peer, child)
    assert read_grammar_state(graph.nodes[child]).history == ("IL", "AL")
    assert form(graph, child) == Q(31, 128)
