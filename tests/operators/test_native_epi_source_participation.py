"""Exact accounting of actual canonical native actions on finite P2 sources.

The supplied clock never advances. Stored diagnostics, observations and lag
memory are declared inputs; actual stages acquire grammar. No rate, source
acquisition, topological birth or detached Mutation permission is inferred.
"""

from copy import deepcopy
from fractions import Fraction as Q

import networkx as nx
import pytest

from tnfr.alias import get_attr
from tnfr.constants import inject_defaults
from tnfr.constants.aliases import ALIAS_EPI
from tnfr.dynamics.selectors import DefaultGlyphSelector, apply_native_operator_batch
from tnfr.operators.coherence import Coherence
from tnfr.operators.dissonance import Dissonance
from tnfr.operators.grammar_debt import read_grammar_state
from tnfr.operators.network_stage import (
    execute_dissonance_stage,
    execute_pointwise_stage,
)
from tnfr.types import require_finite_real_scalar_epi

CORE, PEER = "core", "peer"
NODES = (CORE, PEER)


def _form(graph, node):
    return require_finite_real_scalar_epi(
        get_attr(graph.nodes[node], ALIAS_EPI, strict=True, conv=lambda value: value)
    )


def _source(order=NODES):
    graph = nx.Graph()
    graph.add_nodes_from(order)
    graph.add_edge(CORE, PEER, weight=1.0)
    inject_defaults(graph)
    graph.graph.update(
        _t=2.0,
        RANDOM_SEED=37,
        VALIDATE_OPERATOR_PRECONDITIONS=True,
        GRAMMAR_CANON={"enabled": True},
        GRAMMAR_REJECTION_MODE="raise",
        EDGE_AWARE_ENABLED=True,
        OZ_NOISE_MODE=False,
        IL_PRECONDITIONS={"warn_zero_dnfr": False},
        NAV_RANDOM=False,
        NAV_STRICT=False,
        CLIP_MODE="hard",
        EPI_MIN=-1.0,
        EPI_MAX=1.0,
        ZHIR_THRESHOLD_XI=0.0625,
        glyph_selector=DefaultGlyphSelector(),
    )
    graph.graph["GLYPH_FACTORS"].update(
        AL_boost=0.125,
        EN_mix=0.5,
        IL_dnfr_factor=0.0,
        OZ_dnfr_factor=2.0,
        UM_theta_push=0.5,
        UM_vf_sync=0.5,
        UM_dnfr_reduction=0.5,
        RA_epi_diff=0.5,
        RA_vf_amplification=0.5,
        RA_phase_coupling=0.5,
        SHA_vf_factor=0.5,
        VAL_scale=2.0,
        NUL_scale=0.5,
        NUL_densification_factor=2.0,
        THOL_accel=0.5,
        ZHIR_theta_shift=0.25,
        NAV_eta=0.5,
        NAV_jitter=0.0,
    )
    for node, form in ((CORE, 0.25), (PEER, 0.125)):
        graph.nodes[node].update(
            EPI=form,
            nu_f=1.0,
            theta=0.0,
            delta_nfr=0.0,
            Si=1.0,
            d2EPI=0.0,
            epi_kind="form",
            glyph_history=[],
            # Declared own observations, not generated by zero-duration events.
            epi_time_history=[(0.0, 0.125), (1.0, 0.125), (2.0, form)],
        )
    samples = {node: deepcopy(graph.nodes[node]["epi_time_history"]) for node in graph}
    for glyph in ("IL", "OZ", "IL"):
        if glyph == "OZ":
            execute_dissonance_stage(
                graph,
                Dissonance(),
                (CORE,),
                propagate_to_network=False,
                validate_preconditions=True,
            )
            assert graph.nodes[CORE]["delta_nfr"] == 0.1
            assert graph.nodes[PEER]["delta_nfr"] == 0.0
        else:
            execute_pointwise_stage(
                graph,
                Coherence(),
                tuple(graph),
                phase_locking_coefficient=0.0,
                require_exact_operator=True,
                validate_preconditions=True,
            )
    for node in graph:
        grammar = read_grammar_state(graph.nodes[node])
        expected_history = ("IL", "OZ", "IL") if node == CORE else ("IL", "IL")
        assert grammar.history == expected_history
        assert grammar.u2_debt == 0 and grammar.prior_coherence
        assert graph.nodes[node]["delta_nfr"] == 0.0
        assert graph.nodes[node]["epi_time_history"] == samples[node]
    assert tuple(_form(graph, node) for node in NODES) == (0.25, 0.125)
    return graph


def _batch(graph, memory):
    decisions, epi_trace = [], []
    result = apply_native_operator_batch(
        graph, memory, decision_trace=decisions, epi_trace=epi_trace
    )
    assert result is None
    assert len(epi_trace) == 1
    report = epi_trace[0]
    assert report.completed and report.failure_type is None
    assert report.available and report.unavailability_reasons == ()
    assert report.clock_preserved
    assert report.initial.exact_time == report.final.exact_time == Q(2)
    assert graph.graph["_t"] == 2.0
    assert report.initial.nodes == report.final.nodes == tuple(graph)
    assert all(
        item.returned and item.failure_type is None for item in report.dispatches
    )
    return decisions, report


def _vector(report, expected):
    return tuple(expected[node] for node in report.initial.nodes)


def _assert_accounting(report, expected):
    vector = _vector(report, expected)
    zero = tuple(Q(0) for _ in report.initial.nodes)
    assert report.exact_net_increment == report.exact_dispatch_increment == vector
    assert report.exact_dispatch_variation == tuple(abs(value) for value in vector)
    assert report.exact_outside_dispatch_increment == zero
    assert report.exact_outside_dispatch_variation == zero
    assert len(report.exact_outside_dispatch_increments) == len(report.dispatches) + 1
    assert all(item == zero for item in report.exact_outside_dispatch_increments)
    assert all(type(value) is Q for value in report.exact_net_increment)


@pytest.mark.parametrize("order", [NODES, (PEER, CORE)])
def test_actual_native_al_en_source_retains_sequential_node_order(order):
    graph = _source(order)
    memory = {
        "since_AL": {CORE: graph.graph["AL_MAX_LAG"]},
        "since_EN": {PEER: graph.graph["EN_MAX_LAG"]},
    }
    decisions, report = _batch(graph, memory)
    expected_marks = ("AL", "EN") if order == NODES else ("EN", "AL")
    assert tuple(row.applied_glyph for row in decisions) == expected_marks
    assert all(
        not row.selector_evaluated and row.selection is None for row in decisions
    )
    assert tuple(item.node for item in report.dispatches) == order
    assert tuple(item.glyph for item in report.dispatches) == expected_marks
    assert tuple(item.index for item in report.dispatches) == (0, 1)
    peer_increment = Q(1, 8) if order == NODES else Q(1, 16)
    _assert_accounting(report, {CORE: Q(1, 8), PEER: peer_increment})
    for item in report.dispatches:
        expected = {CORE: Q(0), PEER: Q(0)}
        expected[item.node] = Q(1, 8) if item.node == CORE else peer_increment
        assert item.exact_increment == _vector(report, expected)
        assert item.before.nodes == item.after.nodes == order
        assert item.before.exact_time == item.after.exact_time == Q(2)
    assert _form(graph, CORE) == 3 / 8
    assert Q.from_float(_form(graph, PEER)) == Q(1, 8) + peer_increment
    assert memory["since_AL"][CORE] == memory["since_EN"][PEER] == 0
    assert all(graph.nodes[node]["epi_time_history"] == () for node in graph)


def test_actual_al_then_en_return_has_zero_signed_change_and_nonzero_variation():
    graph = _source()
    initial = tuple(Q.from_float(_form(graph, node)) for node in NODES)
    # Both are due initially; actual AL priority leaves EN due on the next call.
    memory = {
        "since_AL": {CORE: graph.graph["AL_MAX_LAG"]},
        "since_EN": {CORE: graph.graph["EN_MAX_LAG"]},
    }
    first_decisions, first = _batch(graph, memory)
    assert tuple(row.applied_glyph for row in first_decisions) == ("AL", "IL")
    _assert_accounting(first, {CORE: Q(1, 8), PEER: Q(0)})
    assert _form(graph, CORE) == 3 / 8
    assert graph.nodes[CORE]["epi_time_history"] == ()
    second_decisions, second = _batch(graph, memory)
    assert tuple(row.applied_glyph for row in second_decisions) == ("EN", "IL")
    _assert_accounting(second, {CORE: Q(-1, 8), PEER: Q(0)})
    assert tuple(Q.from_float(_form(graph, node)) for node in NODES) == initial
    signed = tuple(
        a + b for a, b in zip(first.exact_net_increment, second.exact_net_increment)
    )
    variation = tuple(
        a + b
        for a, b in zip(first.exact_dispatch_variation, second.exact_dispatch_variation)
    )
    assert signed == (Q(0), Q(0))
    assert variation == (Q(1, 4), Q(0))
    assert first.final.exact_epi == second.initial.exact_epi
    assert graph.nodes[CORE]["epi_time_history"] == ()
    assert read_grammar_state(graph.nodes[CORE]).history[-2:] == ("AL", "EN")


def test_native_no_action_has_no_dispatch_entry_but_retains_actual_peer_action():
    graph = _source()
    graph.graph["NATIVE_ZHIR_ABSTENTION_POLICY"] = "skip"
    graph.nodes[CORE]["Si"] = 0.0
    graph.nodes[CORE]["epi_time_history"] = [(1.0, 0.25), (2.0, 0.25)]
    prior = read_grammar_state(graph.nodes[CORE])
    decisions, report = _batch(graph, {})
    assert decisions[0].requested_glyph == "ZHIR"
    assert decisions[0].status == "abstained" and decisions[0].applied_glyph is None
    assert decisions[1].applied_glyph == "IL"
    assert tuple((item.node, item.glyph) for item in report.dispatches) == (
        (PEER, "IL"),
    )
    assert read_grammar_state(graph.nodes[CORE]) == prior
    _assert_accounting(report, {CORE: Q(0), PEER: Q(0)})


@pytest.mark.parametrize(
    "glyph,expected_form",
    [
        ("AL", Q(3, 8)),
        ("EN", Q(3, 16)),
        ("IL", Q(1, 4)),
        ("OZ", Q(1, 4)),
        ("UM", Q(1, 4)),
        ("RA", Q(3, 16)),
        ("SHA", Q(1, 4)),
        ("VAL", Q(1, 2)),
        ("NUL", Q(1, 8)),
        ("THOL", Q(1, 4)),
        ("ZHIR", Q(1, 4)),
        ("NAV", Q(1, 4)),
        ("REMESH", Q(1, 4)),
    ],
)
def test_all_registered_direct_actions_have_actual_full_population_accounting(
    glyph, expected_form
):
    graph = _source()
    # Explicit supplied selection policy for contract coverage, not a claimed
    # derivation of competition among the thirteen operators.
    graph.graph["glyph_selector"] = lambda _graph, node: glyph if node == CORE else "IL"
    before = read_grammar_state(graph.nodes[CORE])
    decisions, report = _batch(graph, {})
    assert tuple(row.applied_glyph for row in decisions) == (glyph, "IL")
    assert tuple(item.glyph for item in report.dispatches) == (glyph, "IL")
    assert tuple(graph) == NODES
    assert Q.from_float(_form(graph, CORE)) == expected_form
    assert _form(graph, PEER) == 1 / 8
    _assert_accounting(report, {CORE: expected_form - Q(1, 4), PEER: Q(0)})
    assert report.dispatches[0].exact_increment == (expected_form - Q(1, 4), Q(0))
    assert report.dispatches[1].exact_increment == (Q(0), Q(0))
    after = read_grammar_state(graph.nodes[CORE])
    assert after.operator_step == before.operator_step + 1
    assert after.history[-1] == glyph
    if glyph == "OZ":
        assert graph.nodes[CORE]["delta_nfr"] == 0.1
    elif glyph == "THOL":
        assert graph.nodes[CORE]["delta_nfr"] == 1 / 16
        assert graph.nodes[CORE]["d2EPI"] == 1 / 8
        assert graph.number_of_nodes() == 2  # Direct pressure action, no birth.
    elif glyph == "ZHIR":
        assert graph.nodes[CORE]["theta"] == 1 / 4
        assert decisions[0].mutation_certificate.observed_depi_dt == 1 / 8
    elif glyph == "NAV":
        assert graph.nodes[CORE]["delta_nfr"] == 1 / 2
    elif glyph == "REMESH":
        assert "_remesh_warn_step" in graph.graph  # Advisory, no delayed mixing.
    elif glyph in ("SHA", "VAL", "NUL", "RA"):
        expected_capacity = {"SHA": 0.5, "VAL": 2.0, "NUL": 0.5, "RA": 1.5}[glyph]
        assert graph.nodes[CORE]["nu_f"] == expected_capacity
