def test_actual_common_mutation_preserves_relative_source_selection():
    outputs = []
    for mutate in (False, True):
        graph = _source(all_evidence=True)
        _prepare(graph, _ALL)
        if mutate:
            order = (_PEER, _CORE, _MEMBER)
            result = _mutate(graph, _record(graph, _ALL), order)
            observations = result.stage_result.mutation_decision_observations
            assert tuple(o.node for o in observations) == order
            assert all(
                o.trigger_certificate.threshold_gate_satisfied for o in observations
            )
            assert _phase(graph, _CORE) == pytest.approx(0.25, abs=1e-15)
            assert _phase(graph, _MEMBER) == pytest.approx(0.25, abs=1e-15)
            assert _phase(graph, _PEER) == pytest.approx(0.5, abs=1e-15)
        result = _receive(graph)
        assert result.compatibility.selected_sources == (_MEMBER,)
        execute_neighbor_stage(
            graph, Resonance(), (_PEER,), validate_preconditions=True
        )
        outputs.append((_form(graph, _CORE), _form(graph, _PEER)))
    assert outputs == [(7 / 16, 19 / 32)] * 2


