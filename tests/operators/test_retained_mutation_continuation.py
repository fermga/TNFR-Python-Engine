@pytest.mark.parametrize(
    "invalid", ["nonpositive", "stale_endpoint", "zero_capacity", "missing_own_il"]
)
def test_actual_retained_request_rejects_unready_own_source_atomically(invalid):
    graph = _source()
    _prepare(graph)
    if invalid == "nonpositive":
        graph.nodes[_CORE]["epi_time_history"] = [(0.0, 0.75), (1.0, 0.625), (2.0, 0.5)]
    elif invalid == "stale_endpoint":
        graph.nodes[_CORE]["epi_time_history"][-1] = (2.0, 0.625)
    elif invalid == "zero_capacity":
        graph.nodes[_CORE]["nu_f"] = 0.0
    else:
        graph.nodes[_CORE]["_grammar_prior_coherence"] = False
        graph.nodes[_CORE]["glyph_history"] = ["OZ"]
    record = _record(graph)
    before = _plain(graph)
    with pytest.raises(_ERRORS):
        _mutate(graph, record)
    assert _plain(graph) == before


