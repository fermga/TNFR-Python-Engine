_CORE = "core"
_MEMBER = "member"
_PEER = "external"
_ALL = (_CORE, _MEMBER, _PEER)
_ERRORS = (ValueError, RuntimeError, OperatorPreconditionError)


def _form(graph, node):
    return require_finite_real_scalar_epi(get_attr(graph.nodes[node], ALIAS_EPI))


def _phase(graph, node):
    return get_attr(graph.nodes[node], ALIAS_THETA)


def _channels(graph, node):
    return (
        _form(graph, node),
        get_attr(graph.nodes[node], ALIAS_VF),
        get_attr(graph.nodes[node], ALIAS_DNFR),
        graph.nodes[node]["epi_kind"],
    )


def _edges(graph):
    if graph.is_multigraph():
        return tuple(
            (a, b, key, deepcopy(data))
            for a, b, key, data in graph.edges(keys=True, data=True)
        )
    return tuple((a, b, deepcopy(data)) for a, b, data in graph.edges(data=True))


def _plain(graph):
    return structural_proof_signature(
        (
            graph.graph,
            tuple(graph.nodes(data=True)),
            _edges(graph),
            getattr(graph, "_last_operator_applied", None),
        ),
        opaque_references=(graph,),
    )


def _source(graph_type=nx.Graph, *, all_evidence=False, fixed=False):
    graph = graph_type(
        VALIDATE_OPERATOR_PRECONDITIONS=True,
        GRAMMAR_REJECTION_MODE="raise",
        EDGE_AWARE_ENABLED=True,
        CLIP_MODE="hard",
        EPI_MIN=-1.0,
        EPI_MAX=1.0,
        OZ_NOISE_MODE=False,
        _t=2.0,
        RANDOM_SEED=19,
        GLYPH_FACTORS={
            "IL_dnfr_factor": 0.5,
            "OZ_dnfr_factor": 2.0,
            "EN_mix": 0.25,
            "RA_epi_diff": 0.5,
            "RA_phase_coupling": 0.5,
            "RA_vf_amplification": 1.0,
        },
    )
    if fixed:
        graph.graph["GLYPH_FACTORS"]["ZHIR_theta_shift"] = 0.5
    for node, form, phase in (
        (_CORE, 0.5, 0.0),
        (_MEMBER, 0.25, 0.0),
        (_PEER, 0.75, 0.5 if fixed else 0.25),
    ):
        graph.add_node(
            node,
            EPI=form,
            nu_f=1.0,
            theta=phase,
            delta_nfr=0.0625,
            epi_kind="same-form",
            Si=0.5,
            glyph_history=[],
            _grammar_u2_debt=0,
            _grammar_prior_coherence=False,
            _operator_step=0,
        )
        if node == _CORE or all_evidence:
            # Supplied own measured-history fixture, not generated by the word.
            graph.nodes[node]["epi_time_history"] = [
                (0.0, form - 0.25),
                (1.0, form - 0.125),
                (2.0, form),
            ]
    graph.add_edge(_MEMBER, _CORE, weight=0.375, role="retained-port")
    graph.add_edge(_PEER, _CORE, weight=0.625, role="external-port")
    if graph.is_multigraph():
        graph.add_edge(_MEMBER, _CORE, weight=0.0, role="parallel-zero")
    return graph


def _prepare(graph, targets=(_CORE,)):
    histories = {
        node: deepcopy(graph.nodes[node].get("epi_time_history")) for node in targets
    }
    phases = tuple(_phase(graph, node) for node in graph)
    forms = tuple(_form(graph, node) for node in graph)
    execute_pointwise_stage(
        graph,
        Coherence(),
        targets,
        phase_locking_coefficient=0.0,
        require_exact_operator=True,
        validate_preconditions=True,
    )
    execute_dissonance_stage(
        graph, Dissonance(), targets, propagate=False, validate_preconditions=True
    )
    assert tuple(_phase(graph, node) for node in graph) == phases
    assert tuple(_form(graph, node) for node in graph) == forms
    for node in targets:
        assert graph.nodes[node].get("epi_time_history") == histories[node]
        context = read_grammar_state(graph.nodes[node])
        assert context.history == ("IL", "OZ")
        assert context.prior_coherence and context.u2_debt == 1


def _record(graph, members=(_CORE, _MEMBER)):
    return capture_retained_organization(graph, members)


def _mutate(graph, record=None, targets=(_CORE,)):
    return execute_retained_mutation_stage(
        graph,
        _record(graph) if record is None else record,
        targets,
        execution_kwargs={
            "validate_preconditions": True,
            "validate_postconditions": True,
        },
    )


def _policy(gap=0.125, mode="select"):
    return ReceptionCompatibilityPolicy(gap, 0.0, mode=mode)


def _receive(graph, policy=None):
    return execute_eligible_reception_stage(
        graph,
        _CORE,
        _policy() if policy is None else policy,
        execution_kwargs={"validate_preconditions": True, "track_sources": False},
    )


@pytest.mark.parametrize(
    "graph_type", [nx.Graph, nx.DiGraph, nx.MultiGraph, nx.MultiDiGraph]
)
def test_local_actual_mutation_changes_selected_en_and_downstream_ra(graph_type):
    outputs = []
    for mutate in (False, True):
        graph = _source(graph_type)
        _prepare(graph)
        before = _record(graph)
        edges = _edges(graph)
        channels = tuple(_channels(graph, node) for node in graph)
        other_states = deepcopy((dict(graph.nodes[_MEMBER]), dict(graph.nodes[_PEER])))
        assert observe_reception_compatibility(
            graph, _CORE, _policy()
        ).selected_sources == (_MEMBER,)
        if mutate:
            dispatch = _mutate(graph, before)
            assert dispatch.targets == (_CORE,)
            assert dispatch.stage_result.nodes_processed == 1
            assert dispatch.stage_result.glyph == "ZHIR"
            observed = dispatch.stage_result.mutation_decision_observations[0]
            assert observed.node == _CORE and observed._proof_fields_are_intact()
            certificate = observed.trigger_certificate
            assert certificate.observed_depi_dt == 0.125
            assert certificate.predicted_depi_dt == 0.0625
            assert (
                certificate.threshold_gate_satisfied
                and not certificate.predicted_crossed
            )
            assert (
                certificate.physical_time_resolved
                and certificate.current_endpoint_matches_state
            )
            assert certificate.source == "epi_time_history"
            assert observed.destabilizer_operator == "dissonance"
            assert _phase(graph, _CORE) == pytest.approx(0.25, abs=1e-15)
            assert read_grammar_state(graph.nodes[_CORE]).u2_debt == 2
            assert retained_organization_matches_graph(graph, dispatch.after)
            assert not retained_organization_matches_graph(graph, before)
        assert tuple(_channels(graph, node) for node in graph) == channels
        assert (dict(graph.nodes[_MEMBER]), dict(graph.nodes[_PEER])) == other_states
        assert _edges(graph) == edges
        received = _receive(graph)
        assert received.executed
        assert received.compatibility.selected_sources == (
            (_PEER,) if mutate else (_MEMBER,)
        )
        assert _form(graph, _CORE) == (9 / 16 if mutate else 7 / 16)
        execute_neighbor_stage(
            graph, Resonance(), (_PEER,), validate_preconditions=True
        )
        outputs.append((_form(graph, _CORE), _form(graph, _PEER)))
        assert _edges(graph) == edges and graph.graph["_t"] == 2.0
    assert outputs == [(7 / 16, 19 / 32), (9 / 16, 21 / 32)]


