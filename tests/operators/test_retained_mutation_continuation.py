def test_real_derived_child_and_same_time_jumps_supply_no_elapsed_growth():
    graph = _source()
    graph.nodes[_CORE]["delta_nfr"] = 0.125
    _prepare(graph)
    graph.graph.update(
        UM_FUNCTIONAL_LINKS=True,
        UM_BIDIRECTIONAL=True,
        UM_SYNC_VF=False,
        UM_STABILIZE_DNFR=False,
        UM_COMPAT_THRESHOLD=0.5,
    )
    graph.graph["GLYPH_FACTORS"].update(VAL_scale=1.5, UM_theta_push=0.5)
    child = "actual-new-derived-child"
    execute_derived_expansion_stage(
        graph,
        capture_retained_organization(graph, (_CORE,)),
        child,
        DerivedExpansionPolicy(
            source_order="pre_val", form_ratio=0.5, capacity_ratio=0.5
        ),
    )
    execute_coupling_stage(graph, Coupling(), (_CORE,), potential_partner=child)
    assert read_grammar_state(graph.nodes[child]).history == ()
    assert not read_grammar_state(graph.nodes[child]).prior_coherence
    assert len(graph.nodes[child]["epi_history"]) == 1
    assert "epi_time_history" not in graph.nodes[child]
    stale = mutation_trigger_certificate(graph.nodes[_CORE], graph.graph)
    assert not stale.evidence_valid and stale.reason == "stale_physical_endpoint"
    _record_mutation_flow_boundary(graph)
    assert tuple(graph.nodes[_CORE]["epi_time_history"]) == ((2.0, 0.75),)
    assert tuple(graph.nodes[child]["epi_time_history"]) == ((2.0, 0.25),)
    record = _record(graph, (_CORE, child))
    before = _plain(graph)
    with pytest.raises(_ERRORS, match="two|history|threshold"):
        _mutate(graph, record, (child,))
    assert _plain(graph) == before
    assert graph.graph["_t"] == 2.0


