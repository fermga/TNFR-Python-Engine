"""Regional form observations and exact affine-law admission.

The supplied ordered triples fix the frame
``z=(x0-x1)/sqrt(2) + i*(x0+x1-2*x2)/sqrt(6)``. Its orientation is
derived from scalar EPI, not the primitive nodal phase. Exact rational fields
refer to admitted binary64 inputs and the separately materialized canonical
nodal product. Numerical polar estimates have explicit availability statuses.
The affine admission helper checks a separately supplied fine law against
the same mean/Gram observation. Neither selects a pressure law or evolution.
"""

