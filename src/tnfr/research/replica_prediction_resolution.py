def _require(condition, message):
    if not condition:
        raise ValueError(message)


@dataclass(frozen=True)
class ResolutionObservation:
    tube: tuple[I, ...]
    cap: Q
    available: bool
    raw_gaps: tuple[I, ...]
    target_lower: Q
    target_upper: Q
    shifts: tuple[int, ...]
    distances: tuple[tuple[Q, ...], ...]
    threshold_status: str
    threshold: Q | None
    strict_lower_bound: Q | None
    minimizing_assignment: tuple[int, ...]
    zero_allowance_status: str
    exact_state_existence_claimed: bool = False
    actual_error_measured: bool = False
    cause_identified: bool = False
    restricted_minimum_claimed_global_outside_domain: bool = False


def resolve_prediction(tube, cap):
    """Find the critical dilation of the existing closed interval reader.

    The old observer owns raw gaps and the complete branch-domain admission.
    Its operations on shifted intervals are retained exactly. Censoring at
    cap prevents the restricted minimax from becoming an unjustified global
    threshold outside that admitted domain.
    """
    cap = _exact(cap, "allowance domain cap")
    _require(cap >= 0, "allowance domain cap must be nonnegative")
    state = _ten_box(tube)
    observation = observe_prediction(state, cap)
    lower, upper = MARGIN, observation.dilated_target_upper - cap
    if not observation.available:
        return ResolutionObservation(
            state,
            cap,
            False,
            observation.raw_gaps,
            lower,
            upper,
            SHIFTS,
            (),
            "unavailable",
            None,
            None,
            (),
            "unresolved",
        )
    pi = pi_interval()
    distances = []
    for gap in observation.raw_gaps:
        row = []
        for shift in SHIFTS:
            shifted = gap + 2 * shift * pi
            row.append(max(Q(0), lower - shifted.hi, shifted.lo - upper))
        distances.append(tuple(row))
    distances = tuple(distances)
    # Each state retains its best cost and a deterministic attaining word.
    layer = {0: (Q(0), ())}
    for row in distances:
        following = {}
        for total, (cost, word) in layer.items():
            for shift, distance in zip(SHIFTS, row):
                candidate = (max(cost, distance), word + (shift,))
                target = total + shift
                if target not in following or candidate < following[target]:
                    following[target] = candidate
        layer = following
    restricted, word = layer[1]
    within = restricted <= cap
    return ResolutionObservation(
        state,
        cap,
        True,
        observation.raw_gaps,
        lower,
        upper,
        SHIFTS,
        distances,
        "within_domain" if within else "beyond_domain",
        restricted if within else None,
        None if within else cap,
        word if within else (),
        "unresolved" if restricted == 0 else "separated",
    )


def _status_from_admitted(observation, error):
    if not observation.available:
        return "unresolved"
    if observation.threshold_status == "beyond_domain":
        return "separated"
    return "separated" if error < observation.threshold else "unresolved"


def resolution_status(observation, error):
    """Rebuild a supplied result from its primitive tube/cap before consuming it.

    A frozen dataclass is not evidence admission: cached costs, thresholds,
    flags and witnesses must all match the primitive reconstruction.
    """
    error = _exact(error, "queried gap allowance")
    _require(error >= 0, "queried allowance must be nonnegative")
    _require(isinstance(observation, ResolutionObservation), "invalid resolution")
    cap = _exact(observation.cap, "allowance domain cap")
    _require(0 <= error <= cap, "query outside the proved allowance domain")
    rebuilt = resolve_prediction(observation.tube, cap)
    _match(asdict(observation), asdict(rebuilt), "resolution reconstruction")
    return _status_from_admitted(rebuilt, error)


@dataclass(frozen=True)
class RetainedPrediction:
    source: PredictionSource
    allowances: PredictionAllowances
    tubes: tuple[tuple[I, ...], ...]
    observations: tuple[PredictionObservation, ...]
    final_endpoint: tuple[I, ...]
    receipts: tuple[dict, ...] = ()
    final_state_receipt: dict | None = None
    file_bound: bool = False
    endpoint_arithmetic_rebuilt: bool = True
    derivative_or_picard_recomputed: bool = False
    execution_authenticated: bool = False
    prior_producer_replayed: bool = False
    actual_source_trajectory_read: bool = False
    new_integration: bool = False


def _vector(raw, label):
    return tuple(_interval(value) for value in _rows(raw, 10, label))


def admit_prediction_records(
    attempt, source_record, allowances_record, cells, *, allowances
):
    """Rebuild consumed source, Taylor arithmetic and frozen classifications.

    The caller supplies already admitted prior allowances. Artificial records
    can satisfy these arithmetic relationships without valid derivative or
    Picard enclosures; the file reader separately binds the evaluated owners.
    """
    attempt = decode_exact_tree(attempt)
    _require(
        type(attempt) is dict and "allowance_final_state" in attempt,
        "missing allowance source association",
    )
    anchor = _receipt(attempt["allowance_final_state"])
    _match(attempt, prediction_attempt(anchor), "retained prediction attempt")
    if allowances.final_state_receipt is not None:
        _match(anchor, allowances.final_state_receipt, "allowance anchor")
    source = declared_prediction_source()
    _match(decode_exact_tree(source_record), asdict(source), "prediction source")
    _match(
        decode_exact_tree(allowances_record),
        asdict(allowances),
        "prediction allowances",
    )
    records = _rows(cells, CELL_COUNT, "retained prediction cells")
    box, tubes, observations = source.initial_box, [], []
    keys = {
        "time",
        "duration",
        "order",
        "initial_box",
        "tube",
        "series",
        "local_remainder_bounds",
        "increment",
        "endpoint",
        "picard_interior_margin",
        "domain_lower_bounds",
        "method",
    }
    for index, raw in enumerate(records):
        cell = decode_exact_tree(raw)
        _require(
            type(cell) is dict
            and {"cell_index", "step", "allowance", "observation"} <= set(cell),
            "incomplete retained prediction cell",
        )
        _require(
            _integer(cell["cell_index"], "cell index") == index, "cell order differs"
        )
        step = cell["step"]
        _require(type(step) is dict and keys <= set(step), "incomplete Taylor record")
        time = _exact(step["time"], "cell time")
        duration = _exact(step["duration"], "cell duration")
        order = _integer(step["order"], "Taylor order")
        _require(
            time == index * STEP and duration == STEP and order == ORDER,
            "retained clock or numerical policy differs",
        )
        _match(
            step["method"],
            "direct_source_box_Picard_Taylor_dyadic128_v1",
            "step method",
        )
        initial, tube = _vector(step["initial_box"], "initial box"), _vector(
            step["tube"], "whole-time tube"
        )
        series = tuple(
            tuple(_interval(value) for value in _rows(row, ORDER + 1, "Taylor row"))
            for row in _rows(step["series"], 10, "Taylor series")
        )
        remainder = _vector(step["local_remainder_bounds"], "Taylor remainder")
        increment = _vector(step["increment"], "retained increment")
        endpoint = _vector(step["endpoint"], "retained endpoint")
        margin = _exact(step["picard_interior_margin"], "Picard margin")
        _require(margin > 0, "strict Picard premise unavailable")
        _match(step["domain_lower_bounds"], (Q(1),), "smooth domain")
        _require(initial == box, "prediction endpoint chain differs")
        rebuilt_increment, rebuilt_endpoint = reconstruct_box_taylor_arithmetic(
            initial, tube, series, remainder, duration, order=order
        )
        _require(
            increment == rebuilt_increment and endpoint == rebuilt_endpoint,
            "retained prediction arithmetic differs",
        )
        error = allowance_for_cell(index, allowances)
        _match(cell["allowance"], error, "retained gap allowance")
        observation = observe_prediction(tube, error)
        _match(
            cell["observation"], asdict(observation), "retained prediction observation"
        )
        tubes.append(tube)
        observations.append(observation)
        box = endpoint
    return RetainedPrediction(
        source, allowances, tuple(tubes), tuple(observations), box
    )


def read_prediction(repository, *, final_state_receipt):
    """Bind the closed prediction and re-admit its evaluated-source association."""
    root, receipts = Path(repository).resolve(), {}

    def bound_bytes(raw, limit=JSON_LIMIT):
        row = _receipt(raw)
        path = (root / row["path"]).resolve()
        _require(path.is_relative_to(root), "prediction artifact escapes repository")
        _require(row["bytes"] <= limit, "prediction artifact exceeds read budget")
        data = read_bytes_bounded(path, max_bytes=limit)
        _require(
            len(data) == row["bytes"] and sha256_bytes(data) == row["sha256"],
            "prediction byte association differs",
        )
        receipts[row["path"]] = row
        return data

    def record(row):
        return decode_exact_tree(json_loads(bound_bytes(row)))

    anchor = _receipt(final_state_receipt)
    _require(anchor["path"] == FINAL_STATE_PATH, "wrong prediction final manifest")
    final = record(anchor)
    _require(
        type(final) is dict
        and final.get("schema") == "tnfr.replica-reduced-prediction-final.v1",
        "unsupported prediction manifest",
    )
    _require(
        {"artifacts", "evaluated_source", "evaluated_source_archive"} <= set(final),
        "incomplete prediction manifest",
    )
    artifacts = _inventory(final["artifacts"])
    names = tuple(
        PRIOR_DIRECTORY + "/" + name
        for name in (
            "validation-plan.json",
            "execution-result.json",
            "trajectory/attempt.json",
            "trajectory/source.json",
            "trajectory/allowances.json",
            "trajectory/trajectory-result.json",
        )
    )
    cell_names = tuple(
        PRIOR_DIRECTORY + f"/trajectory/cell-{index:03d}.json"
        for index in range(CELL_COUNT)
    )
    _require(
        all(name in artifacts for name in names + cell_names),
        "missing retained prediction evidence",
    )
    _require(
        {
            name
            for name in artifacts
            if name.startswith(PRIOR_DIRECTORY + "/trajectory/cell-")
        }
        == set(cell_names),
        "prediction cell inventory differs",
    )
    plan = record(artifacts[names[0]])
    _require(
        type(plan) is dict and {"source", "source_archive"} <= set(plan),
        "incomplete prediction source plan",
    )
    sources = _inventory(plan["source"])
    _require(
        all(name in sources for name in REQUIRED_SOURCE_NAMES),
        "missing prediction production owner",
    )
    _require(
        _inventory(final["evaluated_source"]) == sources,
        "prediction evaluated source inventory differs",
    )
    archive = _receipt(plan["source_archive"])
    _require(
        _receipt(final["evaluated_source_archive"]) == archive,
        "prediction evaluated archive differs",
    )
    verify_archive_members(
        BytesIO(bound_bytes(archive, ARCHIVE_LIMIT)),
        {name: row["sha256"] for name, row in sources.items()},
        max_bytes=ARCHIVE_LIMIT,
    )
    for name, row in sources.items():
        if name.startswith("src/tnfr/") and name.endswith(".py"):
            bound_bytes(row)
    execution = record(artifacts[names[1]])
    _require(
        type(execution) is dict and "result" in execution,
        "missing retained execution association",
    )
    _require(
        _receipt(execution["result"]) == artifacts[names[5]],
        "prediction result association differs",
    )
    attempt = record(artifacts[names[2]])
    _require(
        type(attempt) is dict and "allowance_final_state" in attempt,
        "missing retained allowance anchor",
    )
    allowances = read_allowances(
        root, final_state_receipt=attempt["allowance_final_state"]
    )
    admitted = admit_prediction_records(
        attempt,
        record(artifacts[names[3]]),
        record(artifacts[names[4]]),
        tuple(record(artifacts[name]) for name in cell_names),
        allowances=allowances,
    )
    result = record(artifacts[names[5]])
    expected = prediction_outcome(admitted.observations)
    _require(type(result) is dict and set(expected) <= set(result), "incomplete result")
    for key, value in expected.items():
        _match(result[key], value, "retained prediction result." + key)
    for row in allowances.receipts:
        _require(
            row["path"] not in receipts or receipts[row["path"]] == row,
            "nested allowance receipt conflicts",
        )
        receipts[row["path"]] = row
    return replace(
        admitted,
        receipts=tuple(receipts[name] for name in sorted(receipts)),
        final_state_receipt=anchor,
        file_bound=True,
    )


@dataclass(frozen=True)
class PredictionResolutionAssessment:
    evidence: RetainedPrediction
    observations: tuple[ResolutionObservation, ...]
    frozen_classifications: tuple[str, ...]
    zero_classifications: tuple[str, ...]
    frozen_time_cover: ReplicaTimeCover
    zero_time_cover: ReplicaTimeCover
    prior_unresolved_indices: tuple[int, ...]
    positive_threshold_indices: tuple[int, ...]
    zero_threshold_indices: tuple[int, ...]
    censored_indices: tuple[int, ...]
    unavailable_indices: tuple[int, ...]
    status: str
    frozen_classifications_reconciled: bool = True
    prior_response_was_inspected: bool = True
    new_integrations: int = 0
    new_error_envelopes: int = 0
    prior_producer_replays: int = 0
    actual_error_measured: bool = False
    cause_identified: bool = False
    exact_target_existence_claimed: bool = False
    independent_predictive_experiment: bool = False
    empirical_validation: bool = False


def assess_prediction_resolution(repository, *, final_state_receipt):
    """Evaluate one finite diagnostic of the same forty-eight retained tubes."""
    evidence = read_prediction(repository, final_state_receipt=final_state_receipt)
    observations = tuple(
        resolve_prediction(tube, evidence.allowances.horizon_gap_upper)
        for tube in evidence.tubes
    )
    frozen = tuple(
        _status_from_admitted(item, allowance_for_cell(index, evidence.allowances))
        for index, item in enumerate(observations)
    )
    _require(
        frozen == tuple(item.status for item in evidence.observations),
        "critical dilation does not reconcile the frozen observer",
    )
    zero = tuple(item.zero_allowance_status for item in observations)
    unresolved = tuple(
        index for index, value in enumerate(frozen) if value == "unresolved"
    )
    positive = tuple(
        index
        for index, item in enumerate(observations)
        if item.threshold is not None and item.threshold > 0
    )
    zeros = tuple(
        index for index, item in enumerate(observations) if item.threshold == 0
    )
    censored = tuple(
        index
        for index, item in enumerate(observations)
        if item.threshold_status == "beyond_domain"
    )
    unavailable = tuple(
        index for index, item in enumerate(observations) if not item.available
    )
    positive_consumer, zero_consumer = set(unresolved) & set(positive), set(
        unresolved
    ) & set(zeros)
    if unavailable or not unresolved:
        status = "resolution_evidence_unavailable"
    elif positive_consumer and zero_consumer:
        status = "mixed_resolution_limits"
    elif positive_consumer:
        status = "positive_thresholds_masked_by_retained_allowance"
    else:
        status = "zero_thresholds_in_retained_observer"
    return PredictionResolutionAssessment(
        evidence,
        observations,
        frozen,
        zero,
        prediction_time_cover(frozen),
        prediction_time_cover(zero),
        unresolved,
        positive,
        zeros,
        censored,
        unavailable,
        status,
    )
