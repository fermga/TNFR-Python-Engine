# TEST 3 -- compare two independently defined orthogonal decompositions
# --------------------------------------------------------------------------- #
def test_independent_orthogonal_splits():
    print("=" * 78)
    print("TEST 3 -- TWO FINITE ORTHOGONAL SPLITS ON DIFFERENT SPACES")
    print("=" * 78)
    # Complete-graph permutation representation.
    G = nx.complete_graph(5)
    nodes = list(G.nodes())
    n = len(nodes)
    mats = automorphism_matrices(G, nodes)
    Pi = symmetric_projector(mats)
    graph_fix = int(round(np.trace(Pi)))
    graph_rest = n - graph_fix
    graph_orth = float(np.linalg.norm(Pi @ (np.eye(n) - Pi)))

    # Independently chosen scalar/traceless Hermitian matrix split.
    d = 2
    tx, ty, tz = su2_generators()
    rest_basis = [tx, ty, tz]  # su(2): traceless, dim d^2 - 1 = 3
    i_d = np.eye(d, dtype=complex)
    scalar_dim = 1
    traceless_dim = d * d - scalar_dim
    colour_orth = max(abs(complex(np.trace(i_d.conj().T @ T))) for T in rest_basis)

    ok = (
        graph_rest >= 1
        and traceless_dim >= 1
        and graph_orth < TOL
        and colour_orth < TOL
        and traceless_dim == len(rest_basis)
    )
    print("  graph model (S_n)    : V        = Fix(S_n) (+) orthogonal rest")
    print(
        f"                         dims     = {graph_fix} (+) {graph_rest}   "
        f"block orthogonality ||Pi(I-Pi)|| = {graph_orth:.2e}"
    )
    print("  colour model (SU(2)) : Hermitian = scalar I (+) traceless basis")
    print(
        f"                         dims     = {scalar_dim} (+) {traceless_dim}   "
        f"block orthogonality max|<I_d, T_a>| = {colour_orth:.2e}"
    )
    print(
        f"  VERDICT: {'PASS' if ok else 'FAIL'} -- both selected finite splits "
        "are orthogonal, but they act on different spaces"
    )
    print("  This shared algebraic pattern does not identify RH and YM obstructions.")
    print()
    return ok


