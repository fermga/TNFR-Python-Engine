# TEST 4 -- compare two externally supplied symmetry-breaking ingredients
# --------------------------------------------------------------------------- #
def test_supplied_symmetry_breakers():
    print("=" * 78)
    print("TEST 4 -- SELECTED DIAGONAL AND SU(2) GENERATORS: INDEPENDENT INPUTS")
    print("=" * 78)
    # A supplied node-distinct diagonal breaks the complete-graph symmetry.
    G = nx.complete_graph(5)
    nodes = list(G.nodes())
    n = len(nodes)
    mats = automorphism_matrices(G, nodes)
    Pi = symmetric_projector(mats)
    eye = np.eye(n)
    # The diagonal comes from an optional adelic model or a local fallback.
    p2, p2_label = selected_per_node_diagonal(n)
    graph_break = max(commutator_norm(p2, P) for P in mats)
    graph_leak = float(np.linalg.norm((eye - Pi) @ (p2 @ (Pi @ eye[:, 0]))))
    graph_breaks_symmetry = graph_break > 1e-3 and graph_leak > 1e-3

    # Independently supplied SU(2) generators do not commute.
    tx, ty, _tz = su2_generators()
    fibre_commutator = commutator_norm(tx, ty)
    fibre_is_noncommutative = fibre_commutator > 1e-3

    verdict_line = "audit unavailable; finite algebra only"
    canon_ok = True
    if _HAVE_AUDIT:
        try:
            report = audit_nonabelian_derivability()
            any_noncomm = any(c.has_noncommuting_generators for c in report.candidates)
            verdict_line = (
                f"{report.verdict} ; "
                f"non-commuting generators on any route = {any_noncomm}"
            )
            canon_ok = report.verdict == "OPEN_DERIVABILITY_GAP" and not any_noncomm
        except Exception as exc:  # pragma: no cover
            verdict_line = f"(repository audit unavailable: {exc})"

    ok = graph_breaks_symmetry and fibre_is_noncommutative and canon_ok
    print(f"  graph input : D = diag({p2_label})")
    print(
        f"                breaks S_n (||[D,P_s]|| = {graph_break:.2f}, leak = "
        f"{graph_leak:.2f})"
    )
    print(
        "  colour input: non-commuting generators [T_x,T_y] != 0 "
        f"(||[T_x,T_y]|| = {fibre_commutator:.3f}) leave the scalar subspace"
    )
    print(f"  repository audit output: {verdict_line}")
    print(
        f"  VERDICT: {'PASS' if ok else 'FAIL'} -- both supplied matrices break "
        "their respective finite symmetries"
    )
    print("  No common origin or shared Millennium-problem role is established.")
    print()
    return ok


