"""Finite commutant comparisons on two independently chosen matrix models.

The benchmark retains the historical Camino-7 calculations but narrows their
scope. On a complete graph it checks that four explicitly listed matrices
``f(A, L)`` commute with the enumerated permutation automorphisms and preserve
the invariant subspace from one symmetric seed. On a separate tensor-product
model it checks that lifts ``M (x) I_2`` commute with sampled transformations
``I (x) U``, scalar phase matrices commute, and selected SU(2) matrices need
not commute.

These checks establish only that the tested finite matrix family is a subset of
the relevant commutants. They neither characterize the engine's reachable set
as an entire commutant nor construct a map from a Riemann or Yang--Mills target
into either finite space. The complementary vector used below is synthetic; it
is not ``S(T)``. The colour model and its U(1)/SU(2) groups are external choices,
not a gauge selected or generated by TNFR. Similar-looking orthogonal splittings
therefore do not identify the two Millennium-problem obstructions.

The optional package audit is reported as another model output. It does not
turn these finite identities into a derivation from the nodal equation.

Run:
    python benchmarks/commutant_bridge.py

Status: RESEARCH benchmark; finite algebra and negative identification result.
"""

